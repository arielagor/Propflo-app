/**
 * Google Drive API Integration
 */
export async function uploadLeaseToDrive(lease: LeaseAgreement): Promise<{ id: string; name: string; webViewLink?: string }> {
  const token = await getAccessToken();
  if (!token) throw new Error("Google Workspace authentication required. Please sign in with Google.");

  const fileContent = `=====================================================
PROPFLOW ENTERPRISE - EXECUTED LEASE AGREEMENT
=====================================================
Property: ${lease.propertyName}
Unit: ${lease.unitNumber}
Tenant: ${lease.tenantName} (${lease.tenantEmail})
Monthly Rent: $${lease.monthlyRent.toLocaleString()}
Security Deposit: $${lease.securityDeposit.toLocaleString()}
Term: ${lease.startDate} to ${lease.endDate}
Status: ${lease.status.toUpperCase()}

ELECTRONIC SIGNATURE AUDIT TRAIL:
Signed By: ${lease.tenantName}
Timestamp: ${lease.signedAt || new Date().toISOString()}
Signature Verification Token: PROPHASH-${lease.id.slice(0, 8)}-VERIFIED
E-Sign Consent: ${lease.termsAccepted ? 'ACCEPTED BY LESSEE' : 'PENDING'}

AGREEMENT TERMS:
${lease.terms.map((t, idx) => `${idx + 1}. ${t}`).join('\n')}

=====================================================
Generated by PropFlow Real Estate Bureaucracy System
=====================================================`;

  const metadata = {
    name: `Lease_${lease.propertyName.replace(/\s+/g, '_')}_Unit_${lease.unitNumber}_${lease.tenantName.replace(/\s+/g, '_')}.txt`,
    mimeType: 'text/plain',
  };

  const form = new FormData();
  form.append('metadata', new Blob([JSON.stringify(metadata)], { type: 'application/json' }));
  form.append('file', new Blob([fileContent], { type: 'text/plain' }));

  const res = await fetch('https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,webViewLink', {
    method: 'POST',
    headers: { Authorization: `Bearer ${token}` },
    body: form,
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to upload lease to Google Drive');
  }

  return res.json();
}

