/**
 * Google Sheets API Integration
 */
export async function exportRentRollToSheets(payments: RentPayment[]): Promise<{ spreadsheetId: string; url: string }> {
  const token = await getAccessToken();
  if (!token) throw new Error("Google Workspace authentication required.");

  const title = `PropFlow Rent Roll & Billing Ledger - ${new Date().toLocaleDateString('en-US', { month: 'short', year: 'numeric' })}`;
  
  // 1. Create spreadsheet
  const createRes = await fetch('https://sheets.googleapis.com/v4/spreadsheets', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      properties: { title },
      sheets: [
        {
          properties: { title: 'Rent Collection' },
          data: [
            {
              startRow: 0,
              startColumn: 0,
              rowData: [
                {
                  values: [
                    { userEnteredValue: { stringValue: 'Unit' } },
                    { userEnteredValue: { stringValue: 'Tenant' } },
                    { userEnteredValue: { stringValue: 'Period' } },
                    { userEnteredValue: { stringValue: 'Amount ($)' } },
                    { userEnteredValue: { stringValue: 'Due Date' } },
                    { userEnteredValue: { stringValue: 'Status' } },
                    { userEnteredValue: { stringValue: 'Payment Method' } },
                    { userEnteredValue: { stringValue: 'Ref Number' } },
                  ]
                },
                ...payments.map(p => ({
                  values: [
                    { userEnteredValue: { stringValue: p.unitNumber } },
                    { userEnteredValue: { stringValue: p.tenantName } },
                    { userEnteredValue: { stringValue: p.period } },
                    { userEnteredValue: { numberValue: p.amount } },
                    { userEnteredValue: { stringValue: p.dueDate } },
                    { userEnteredValue: { stringValue: p.status.toUpperCase() } },
                    { userEnteredValue: { stringValue: p.paymentMethod || 'N/A' } },
                    { userEnteredValue: { stringValue: p.referenceNumber || 'N/A' } },
                  ]
                }))
              ]
            }
          ]
        }
      ]
    })
  });

  if (!createRes.ok) {
    const err = await createRes.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to create Google Sheet');
  }

  const data = await createRes.json();
  return {
    spreadsheetId: data.spreadsheetId,
    url: `https://docs.google.com/spreadsheets/d/${data.spreadsheetId}/edit`,
  };
}

/**
 * Google Calendar API Integration
 */
export async function scheduleMaintenanceInCalendar(
  request: MaintenanceRequest,
  startTimeIso: string
): Promise<{ id: string; htmlLink: string }> {
  const token = await getAccessToken();
  if (!token) throw new Error("Google Workspace authentication required.");

  const start = new Date(startTimeIso);
  const end = new Date(start.getTime() + 2 * 60 * 60 * 1000); // 2 hours duration

  const event = {
    summary: `[PropFlow Maintenance] ${request.title} - Unit ${request.unitNumber}`,
    description: `Category: ${request.category.toUpperCase()}\nPriority: ${request.priority.toUpperCase()}\nLessee: ${request.lesseeName} (${request.lesseeEmail})\n\nIssue Details: ${request.description}\n\nAssigned Vendor: ${request.assignedVendor || 'Pending Dispatch'}\nVendor Contact: ${request.vendorContact || 'N/A'}`,
    location: `${request.propertyName}, Unit ${request.unitNumber}`,
    start: { dateTime: start.toISOString() },
    end: { dateTime: end.toISOString() },
    reminders: {
      useDefault: false,
      overrides: [
        { method: 'email', minutes: 24 * 60 },
        { method: 'popup', minutes: 30 },
      ]
    }
  };

  const res = await fetch('https://www.googleapis.com/calendar/v3/calendars/primary/events', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(event),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to schedule event in Google Calendar');
  }

  return res.json();
}

/**
 * Gmail API Integration
 */
export async function sendEmailViaGmail(
  to: string,
  subject: string,
  bodyContent: string
): Promise<{ id: string }> {
  const token = await getAccessToken();
  if (!token) throw new Error("Google Workspace authentication required.");

  const emailLines = [
    `To: ${to}`,
    `Subject: ${subject}`,
    'Content-Type: text/plain; charset=utf-8',
    'MIME-Version: 1.0',
    '',
    bodyContent,
  ];

  const rawMessage = emailLines.join('\r\n');
  const base64Encoded = btoa(unescape(encodeURIComponent(rawMessage)))
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');

  const res = await fetch('https://gmail.googleapis.com/gmail/v1/users/me/messages/send', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ raw: base64Encoded }),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to dispatch email via Gmail');
  }

  return res.json();
}

/**
 * Google Tasks API Integration
 */
export async function createGoogleTask(
  title: string,
  notes: string,
  dueDateIso?: string
): Promise<{ id: string; title: string }> {
  const token = await getAccessToken();
  if (!token) throw new Error("Google Workspace authentication required.");

  const taskPayload: any = {
    title,
    notes,
  };
  if (dueDateIso) {
    taskPayload.due = new Date(dueDateIso).toISOString();
  }

  const res = await fetch('https://tasks.googleapis.com/tasks/v1/lists/@default/tasks', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(taskPayload),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to create task in Google Tasks');
  }

  return res.json();
}

/**
 * Google Contacts (People API)
 */
export async function syncTenantContact(
  givenName: string,
  familyName: string,
  email: string,
  phone?: string
): Promise<{ resourceName: string }> {
  const token = await getAccessToken();
  if (!token) throw new Error("Google Workspace authentication required.");

  const contactData: any = {
    names: [{ givenName, familyName }],
    emailAddresses: [{ value: email, type: 'work' }],
  };

  if (phone) {
    contactData.phoneNumbers = [{ value: phone, type: 'mobile' }];
  }

  const res = await fetch('https://people.googleapis.com/v1/people:createContact', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(contactData),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to sync contact with Google Contacts');
  }

  return res.json();
}
